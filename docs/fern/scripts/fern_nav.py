"""Generate the nightly Fern navigation from page frontmatter.

Builds docs/fern/versions/nightly.yml from two sources:

  docs/fern/nav-skeleton.yml  Navigation entries that are not pages: top-level
                              sections without an overview page, and external links.
  `nav` frontmatter key       Declared by every .mdx file under docs/ (outside
                              docs/fern/). Either `nav: false` to leave the page out
                              of the navigation, or a mapping with these fields:

      parent  Required. `root`, the `id` of a skeleton entry, or the `id` of a page.
      order   Required. Integer sort key among siblings.
      slug    URL slug of the page. Fern derives one from the label when omitted.
      label   Navigation label. Defaults to the page `title`.
      id      Lets other pages name this page as their `parent`. A page with
              children is rendered as a section whose overview is the page itself.

Subcommands:
  generate          Write docs/fern/versions/nightly.yml.
  generate --check  Fail if nightly.yml is out of date or the nav metadata is invalid.
"""

import argparse
import difflib
import json
import re
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[3]
DOCS_DIR = REPO_ROOT / "docs"
FERN_DIR = DOCS_DIR / "fern"
SKELETON = FERN_DIR / "nav-skeleton.yml"
NIGHTLY_NAV = FERN_DIR / "versions" / "nightly.yml"

ROOT_ID = "root"
HEADER = (
    "# Generated by docs/fern/scripts/fern_nav.py from page frontmatter and\n"
    "# docs/fern/nav-skeleton.yml. Do not edit by hand.\n"
)
FRONTMATTER_RE = re.compile(r"\A---\r?\n(.*?)\r?\n---[ \t]*\r?\n", re.S)
YAML_SPECIAL_START = tuple("-?:,[]{}#&*!|>'\"%@`")


class Node:
    def __init__(self, kind, label, parent, order, source, **fields):
        self.kind = kind
        self.label = label
        self.parent = parent
        self.order = order
        self.source = source
        self.id = fields.get("id")
        self.path = fields.get("path")
        self.slug = fields.get("slug")
        self.skip_slug = fields.get("skip_slug", False)
        self.href = fields.get("href")
        self.children = []


def read_frontmatter(path):
    match = FRONTMATTER_RE.match(path.read_text(encoding="utf-8"))
    if not match:
        return {}
    data = yaml.safe_load(match.group(1))
    return data if isinstance(data, dict) else {}


def check_position(nav, source, errors):
    if not isinstance(nav.get("parent"), str):
        errors.append(f"{source}: nav.parent must be a string.")
    if not isinstance(nav.get("order"), int) or isinstance(nav.get("order"), bool):
        errors.append(f"{source}: nav.order must be an integer.")


def load_skeleton(errors):
    entries = yaml.safe_load(SKELETON.read_text(encoding="utf-8")) or []
    nodes = []
    for i, entry in enumerate(entries):
        source = f"{SKELETON.relative_to(REPO_ROOT)} entry {i + 1}"
        entry = {"parent": ROOT_ID, **entry}
        check_position(entry, source, errors)
        if "section" in entry:
            if not entry.get("id"):
                errors.append(f"{source}: sections need an id.")
            nodes.append(
                Node(
                    "section",
                    entry["section"],
                    entry["parent"],
                    entry.get("order"),
                    source,
                    id=entry.get("id"),
                    slug=entry.get("slug"),
                    skip_slug=entry.get("skip-slug", False),
                )
            )
        elif "link" in entry:
            nodes.append(
                Node(
                    "link",
                    entry["link"],
                    entry["parent"],
                    entry.get("order"),
                    source,
                    id=entry.get("id"),
                    href=entry.get("href"),
                )
            )
        else:
            errors.append(f"{source}: expected a 'section' or 'link' key.")
    return nodes


def load_pages(errors):
    nodes = []
    for path in sorted(DOCS_DIR.rglob("*.mdx")):
        if FERN_DIR in path.parents:
            continue
        rel = path.relative_to(DOCS_DIR).as_posix()
        source = f"docs/{rel}"
        frontmatter = read_frontmatter(path)
        nav = frontmatter.get("nav")
        if nav is False:
            continue
        if not isinstance(nav, dict):
            errors.append(
                f"{source}: add a `nav` frontmatter key (a mapping, or `nav: false` "
                "to leave the page out of the navigation)."
            )
            continue
        check_position(nav, source, errors)
        label = nav.get("label") or frontmatter.get("title")
        if not label:
            errors.append(f"{source}: set nav.label or the page title.")
            continue
        nodes.append(
            Node(
                "page",
                str(label),
                nav.get("parent"),
                nav.get("order"),
                source,
                id=nav.get("id"),
                path=rel,
                slug=nav.get("slug"),
            )
        )
    return nodes


def build_tree(nodes, errors):
    by_id = {}
    for node in nodes:
        if node.id is None:
            continue
        if node.id == ROOT_ID or node.id in by_id:
            errors.append(f"{node.source}: id {node.id!r} is already used.")
        else:
            by_id[node.id] = node

    root = Node("root", "", None, 0, "root")
    for node in nodes:
        parent = root if node.parent == ROOT_ID else by_id.get(node.parent)
        if parent is None:
            errors.append(f"{node.source}: unknown nav.parent {node.parent!r}.")
        elif parent.kind == "link":
            errors.append(f"{node.source}: nav.parent {node.parent!r} is a link.")
        else:
            parent.children.append(node)

    reached = set()
    seen_slugs = {}

    def visit(node, slug_path):
        node.children.sort(key=lambda child: (child.order, child.label))
        for child in node.children:
            reached.add(id(child))
            child_path = slug_path
            if child.slug and not child.skip_slug:
                child_path = f"{slug_path}/{child.slug.strip('/')}"
                if child_path in seen_slugs:
                    errors.append(
                        f"{child.source}: slug path {child_path or '/'!r} is also used by "
                        f"{seen_slugs[child_path]}."
                    )
                seen_slugs[child_path] = child.source
            if child.kind == "section" and not child.children:
                errors.append(f"{child.source}: section {child.label!r} has no pages.")
            visit(child, child_path)

    visit(root, "")
    for node in nodes:
        if id(node) not in reached and (node.parent == ROOT_ID or node.parent in by_id):
            errors.append(f"{node.source}: nav.parent chain does not reach root (cycle?).")
    return root


def yaml_scalar(value):
    text = str(value)
    if (
        not text
        or text != text.strip()
        or text.startswith(YAML_SPECIAL_START)
        or ": " in text
        or " #" in text
        or text.endswith(":")
    ):
        return json.dumps(text)
    return text


def render(nodes, indent, lines):
    pad = " " * indent
    for node in nodes:
        kind = "section" if node.children else node.kind
        lines.append(f"{pad}- {kind}: {yaml_scalar(node.label)}")
        if node.href:
            lines.append(f"{pad}  href: {node.href}")
        if node.path:
            lines.append(f"{pad}  path: ../../{node.path}")
        if node.slug:
            lines.append(f"{pad}  slug: {node.slug}")
        if node.skip_slug:
            lines.append(f"{pad}  skip-slug: true")
        if node.children:
            lines.append(f"{pad}  contents:")
            render(node.children, indent + 4, lines)


def generate_nav():
    errors = []
    nodes = load_skeleton(errors) + load_pages(errors)
    root = build_tree(nodes, errors) if not errors else None
    if errors:
        for error in errors:
            print(f"::error::{error}", file=sys.stderr)
        raise SystemExit(f"Found {len(errors)} navigation error(s).")
    lines = ["navigation:"]
    render(root.children, 2, lines)
    return HEADER + "\n".join(lines) + "\n"


def cmd_generate(args):
    nav_text = generate_nav()
    rel = NIGHTLY_NAV.relative_to(REPO_ROOT)
    current = NIGHTLY_NAV.read_text(encoding="utf-8") if NIGHTLY_NAV.exists() else ""
    if not args.check:
        NIGHTLY_NAV.write_text(nav_text, encoding="utf-8")
        print(f"Wrote {rel}.")
        return
    if current == nav_text:
        print(f"{rel} is up to date.")
        return
    sys.stdout.writelines(
        difflib.unified_diff(
            current.splitlines(keepends=True),
            nav_text.splitlines(keepends=True),
            fromfile=f"{rel} (committed)",
            tofile=f"{rel} (generated)",
        )
    )
    raise SystemExit(
        f"::error::{rel} is out of date. Run `python3 docs/fern/scripts/fern_nav.py generate` "
        "and commit the result."
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    subparsers = parser.add_subparsers(dest="command", required=True)

    generate = subparsers.add_parser("generate", help="Write versions/nightly.yml.")
    generate.add_argument(
        "--check",
        action="store_true",
        help="Do not write; fail if nightly.yml is out of date or the nav metadata is invalid.",
    )
    generate.set_defaults(func=cmd_generate)

    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
